/**
 * Build discern.sh's generated design-system surface.
 *
 * React is an authoring adapter only: this script renders the homepage and
 * shared brand to static HTML, writes deterministic CSS/assets, and ships no
 * React runtime.
 */

import { buildReleaseCatalogue } from "./releases/catalogue.ts";

import {
  type BuildSummary,
  emitDesignSystemRuntime,
} from "discern-design-system/runtime";
import {
  DESIGN_SYSTEM_BUNDLES,
  type DesignSystemBundleName,
} from "./design_system.ts";
import { SITE_APPEARANCE } from "./appearance.ts";
import { MARKETING_PAGES } from "./marketing_pages.ts";
import { renderDiscernBrand } from "./ui/components/Brand.tsx";
import { formatGeneratedText } from "./page-src/format-generated.ts";
import { renderMarketingPage } from "./renderers.ts";

const SITE_ROOT = new URL("./", import.meta.url);
const SOURCE_ROOT = new URL("page-src/", SITE_ROOT);

/** Public files produced by the site build and therefore forbidden from Git. */
export const GENERATED_SITE_OUTPUTS = [
  ...MARKETING_PAGES.map((page) => page.page),
  "pages/assets/design-system/",
  "pages/fragments/",
  "pages/release-catalogue.json",
] as const;

/** Page-owned assets copied verbatim into the compositions bundle. */
export const COPIED_PAGE_ASSETS = [
  "agents.css",
  "agents.js",
  "campaign.css",
  "copy-prompt.js",
  "landing.css",
  "map.css",
  "releases.css",
  "trust.css",
] as const;

/** Old generated pages removed on every build so local previews cannot retain them. */
export const RETIRED_SITE_OUTPUTS = [
  "pages/design-system-demo.html",
  "pages/content-design-demo.html",
  "pages/v2.html",
  "pages/agents.md",
] as const;

const ASSET_ROOT = new URL("pages/assets/design-system/", SITE_ROOT);
const FRAGMENT_ROOT = new URL("pages/fragments/", SITE_ROOT);
const BRAND_FRAGMENT_OUTPUT = new URL("brand.html", FRAGMENT_ROOT);
const COMPOSITION_ASSET_ROOT = new URL(
  DESIGN_SYSTEM_BUNDLES.compositions.output,
  SITE_ROOT,
);

/** Remove an output URL recursively while accepting a missing destination. */
async function removeIfPresent(url: URL): Promise<void> {
  try {
    await Deno.remove(url, { recursive: true });
  } catch (error) {
    if (!(error instanceof Deno.errors.NotFound)) throw error;
  }
}

/** Copy source text into the composition bundle with a provenance banner. */
async function writeGeneratedCopy(
  source: string,
  destination: string,
): Promise<void> {
  const body = await Deno.readTextFile(new URL(source, SOURCE_ROOT));
  await Deno.writeTextFile(
    new URL(destination, COMPOSITION_ASSET_ROOT),
    `/* Generated by site/build.ts from site/page-src/${source}. Do not edit. */\n${body}`,
  );
}

/** Generate one selected design-system bundle and return its build summary. */
async function emitBundle(name: DesignSystemBundleName): Promise<BuildSummary> {
  const selection = DESIGN_SYSTEM_BUNDLES[name];
  return await emitDesignSystemRuntime({
    outputRoot: new URL(selection.output, SITE_ROOT),
    components: selection.components,
    groups: selection.groups,
    assets: selection.assets,
    appearanceScopes: SITE_APPEARANCE.appearanceScopes,
  });
}

/** Rebuild the complete ignored public design-system surface from source. */
export async function buildSite(): Promise<void> {
  for (const output of [...GENERATED_SITE_OUTPUTS, ...RETIRED_SITE_OUTPUTS]) {
    await removeIfPresent(new URL(output, SITE_ROOT));
  }

  await buildReleaseCatalogue();
  await Deno.mkdir(ASSET_ROOT, { recursive: true });
  await Deno.mkdir(FRAGMENT_ROOT, { recursive: true });
  await emitBundle("docs");
  const summary = await emitBundle("compositions");
  for (const asset of COPIED_PAGE_ASSETS) {
    await writeGeneratedCopy(asset, asset);
  }
  for (const page of MARKETING_PAGES) {
    await Deno.writeTextFile(
      new URL(page.page, SITE_ROOT),
      await formatGeneratedText(renderMarketingPage(page.route), "html"),
    );
  }
  await Deno.writeTextFile(BRAND_FRAGMENT_OUTPUT, renderDiscernBrand());

  console.log(
    `Built the shared Brand fragment, ${MARKETING_PAGES.length} marketing pages, and design-system bundles from ${summary.components} components and ${summary.tokens} tokens.`,
  );
}

if (import.meta.main) await buildSite();
