/**
 * The wall's built assets: its stylesheets, its island bundle, and how the
 * build names that bundle. Build and server code use this module; the browser
 * island has no need of it.
 */
import { encodeHex } from "@std/encoding/hex";
import { WALL_HOST_ID } from "./host.ts";

/** The wall's stylesheets, in cascade order, copied beside the homepage's bundle. */
export const WALL_STYLESHEETS = [
  "wall.css",
  "wall-card.css",
  "wall-glyph.css",
  "wall-interactions.css",
  "wall-tuning.css",
] as const;

/** The island's browser entry, relative to the repository root. */
export const WALL_ISLAND_ENTRY = "site/wall/island.tsx";

/** Hex characters of the bundle's SHA-256 digest carried in its file name. */
export const WALL_ISLAND_HASH_LENGTH = 16;

const WALL_ISLAND_FILE = new RegExp(
  `^wall-island\\.([0-9a-f]{${WALL_ISLAND_HASH_LENGTH}})\\.js$`,
);

/**
 * Generated files a page links by a name only the build knows. The build
 * passes them to the page renderers. A render without them carries the page's
 * whole content and links none of them, which is all a reader of its prose
 * needs.
 */
export interface BuiltAssets {
  /** The homepage island bundle, by file name beside the wall's stylesheets. */
  readonly wallIsland?: string;
}

/** The content hash a wall island file name carries, or nothing for any other file. */
export function wallIslandContentHash(fileName: string): string | undefined {
  return WALL_ISLAND_FILE.exec(fileName)?.[1];
}

/**
 * Marks a React build leaves in any script that carries its runtime. They are
 * string constants, so they survive bundling and minification under any file
 * name; a script's address says nothing about what was bundled into it.
 */
const REACT_RUNTIME_MARKS =
  /react\.element|react\.transitional\.element|__SECRET_INTERNALS_DO_NOT_USE_OR_YOU_WILL_BE_FIRED|__CLIENT_INTERNALS_DO_NOT_USE_OR_WARN_USERS_THEY_CANNOT_UPGRADE/;

/** Whether script text carries a React runtime, whatever the file is called. */
export function carriesReactRuntime(script: string): boolean {
  return REACT_RUNTIME_MARKS.test(script);
}

/**
 * What keeps script text from being the wall island, or nothing when it is
 * one. The island hydrates the host element with React, so its bundle names
 * that element and carries a React runtime. A bundler that ends without a
 * fault and with empty or partial output gives a script with neither.
 */
export function wallIslandFault(script: string): string | undefined {
  if (!script.includes(WALL_HOST_ID)) {
    return `it never names the host element "${WALL_HOST_ID}"`;
  }
  if (!carriesReactRuntime(script)) {
    return "it carries no React runtime to hydrate with";
  }
  return undefined;
}

/** The island as the build publishes it: a file name and that file's text. */
export interface WallIslandFile {
  readonly file: string;
  readonly body: string;
}

/**
 * Turn the bundle of the island's entry into the file the build publishes:
 * the bundle under a banner, named after the digest of the file's own bytes,
 * so a page can never pair with a bundle built from other markup. This is the
 * one place an island gets its name, and a bundle that is not the island is
 * refused here, so the build cannot publish a homepage whose controls never
 * come alive.
 */
export async function wallIslandFile(bundle: string): Promise<WallIslandFile> {
  const fault = wallIslandFault(bundle);
  if (fault !== undefined) {
    throw new Error(
      `the bundle of ${WALL_ISLAND_ENTRY} is not the wall island: ${fault}`,
    );
  }
  const body =
    `/* Generated by site/build.ts from ${WALL_ISLAND_ENTRY}. Do not edit. */\n${bundle}`;
  const digest = await crypto.subtle.digest(
    "SHA-256",
    new TextEncoder().encode(body),
  );
  const hash = encodeHex(digest).slice(0, WALL_ISLAND_HASH_LENGTH);
  return { file: `wall-island.${hash}.js`, body };
}
