/**
 * Framing authority for committed generated inventories. Member wording stays
 * with the member registry unless a policy says otherwise; titles, banners,
 * explanatory framing, renderer identity, documentation exposure, and guard
 * tests live here so a generator cannot invent its own account.
 */

/** How one inventory obtains the wording for each generated member. */
export type InventoryMemberWordingAuthority =
  | {
    readonly kind: "co-located";
    readonly module: string;
    readonly exportName: string;
  }
  | {
    readonly kind: "shared-policy";
    readonly module: string;
    readonly exportName: string;
  };

/** One inventory's complete projection declaration. */
export interface GeneratedInventoryPolicy {
  readonly artifactPath: string;
  readonly banner: string;
  readonly title: string;
  readonly subtitle: string;
  readonly framing: readonly string[];
  readonly memberWording: InventoryMemberWordingAuthority;
  readonly renderer: {
    readonly module: string;
    readonly exportName: string;
  };
  readonly documentation: string;
  readonly tests: readonly string[];
}

