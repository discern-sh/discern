Deno.test("plain agent accounts render marked as Coding agent, benefits marked, tips cited", () => {
  const doc = renderFeatureCanonPlainDoc();
  const carriers = agentExperienceNodes();
  if (carriers.length > 0) {
    assertStringIncludes(doc, "## What the coding agent sees");
    assertStringIncludes(
      doc,
      ` · ${carriers.length} accounts of what the coding agent experiences`,
    );
    for (const { node } of carriers) {
      assertStringIncludes(
        doc,
        `**Coding agent:** _${node.plain.agent}_`,
        `plain agent account renders unmarked: ${node.id}`,
      );
    }
    // Hints render in the plain register as tips, singular and plural.
    assertStringIncludes(doc, "(tip: `");
    assertStringIncludes(doc, "(tips: `");
  }
  for (
    const { node } of allFeatureNodes().filter(({ node }) =>
      node.kind === "benefit"
    )
  ) {
    assertStringIncludes(
      doc,
      `**${node.plain.title}** _(benefit)_`,
      `plain benefit node renders unmarked: ${node.id}`,
    );
  }
});

Deno.test("command-mention extraction discriminates (positive controls)", () => {
  assertEquals(mentionedVerbs("run `discern done` then `discern accept`"), [
    "done",
    "accept",
  ]);
  assertEquals(mentionedVerbs("`discern worktree prune` reclaims"), [
    "worktree",
  ]);
  assertEquals(
    mentionedVerbs("bare `discern` opens the desk; `discern.toml` is config"),
    [],
  );
});

Deno.test("surface keys parse and malformed keys fail loudly", () => {
  assertEquals(parseSurfaceKey("verb:done"), { set: "verb", member: "done" });
  assertEquals(parseSurfaceKey("no-colon"), undefined);
  // The tree's own claims all parse — allSurfaceClaims throws otherwise.
  assert(allSurfaceClaims().length > 0, "the canon claims surfaces by design");
});
