Deno.test("the rendered page carries the banner, every node, and the coverage appendix", () => {
  const doc = renderFeatureCanonDoc();
  assertStringIncludes(doc, "<!-- GENERATED by `deno task codegen`");
  for (const { node } of allFeatureNodes()) {
    assertStringIncludes(
      doc,
      `**${node.title}**`,
      `no rendering for node: ${node.id}`,
    );
  }
  for (const claim of allSurfaceClaims()) {
    assertStringIncludes(
      doc,
      `- \`${claim.member}\` — `,
      `coverage appendix misses claimed member: ${claim.set}:${claim.member}`,
    );
  }
});

Deno.test("benefit nodes are marked in the rendered tree", () => {
  const doc = renderFeatureCanonDoc();
  const benefits = allFeatureNodes().filter(({ node }) =>
    node.kind === "benefit"
  );
  assert(benefits.length > 0, "the canon carries benefit nodes by design");
  for (const { node } of benefits) {
    assertStringIncludes(
      doc,
      `**${node.title}** *(benefit)*`,
      `benefit node renders unmarked: ${node.id}`,
    );
  }
});

Deno.test("agent-experience accounts render marked, indexed, and counted", () => {
  const doc = renderFeatureCanonDoc();
  const carriers = agentExperienceNodes();
  if (carriers.length === 0) return;
  assertStringIncludes(doc, "## The agent's-eye view");
  assertStringIncludes(doc, ` · ${carriers.length} agent-experience accounts`);
  for (const { node } of carriers) {
    assertStringIncludes(
      doc,
      `**Agent:** *${node.agent}*`,
      `agent account renders unmarked: ${node.id}`,
    );
  }
});

// Every `discern <verb>` mention in canon prose must name a live verb — the
// same command-reference discipline the hint corpus and the map's fenced
// examples are held to, so a rename fails the canon mechanically.

const COMMAND_MENTION = /`discern ([a-z][a-z-]*)/g;

function mentionedVerbs(text: string): string[] {
  return [...text.matchAll(COMMAND_MENTION)].map((m) => m[1] ?? "");
}

Deno.test("every discern command mentioned in canon prose is a live verb", () => {
  for (const { node } of allFeatureNodes()) {
    const texts = [
      node.what,
      node.why ?? "",
      node.agent ?? "",
      node.plain.title,
      node.plain.what,
      node.plain.why ?? "",
      node.plain.agent ?? "",
    ];
    for (const text of texts) {
      for (const verb of mentionedVerbs(text)) {
        assert(
          KNOWN_VERBS.has(verb),
          `node ${node.id} mentions \`discern ${verb}\`, which is not a live verb`,
        );
      }
    }
  }
});

