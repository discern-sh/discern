/**
 * The generated register Vale styles stay in lockstep with their registry
 * (`VALE_STYLE_RULES` in `scripts/brand/vale.ts`): every committed style
 * file matches its renderer byte-for-byte, every style directory contains
 * exactly the rendered set, the canonical-sets entry declares exactly the
 * live artifacts, and every rule's source citations resolve against the
 * voice registry — so a rule added to the registry fails the gate until
 * the styles regenerate, and a renamed source strands nothing.
 *
 * The partition guard is the audited boundary behind "to the extent
 * practical": every proposed mechanical check in the copy review is either
 * cited by a generated rule or carries exactly one recorded disposition in
 * `VALE_DISPOSITIONS` — never both, never neither — so a new proposal
 * cannot land without enforcement or a reason on record.
 */

