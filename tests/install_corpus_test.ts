/**
 * The install corpus proves ADR 0014's keystone invariant on real captured
 * installations: an installation captured at a past schema and brought
 * forward by `discern upgrade` matches a fresh installation from the current
 * build in everything discern maintains. The comparison follows the
 * file-ownership registry: Generated and Shared artifacts converge byte for
 * byte, `discern.toml` converges in its managed projection, and project-owned
 * seeds are the project's and converge by presence. The corpus itself is
 * frozen by its manifests, and `SCHEMA_VERSION` cannot advance past the newest
 * captured schema plus one.
 */

